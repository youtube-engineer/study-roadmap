-- ============================================================================
-- service_role への GRANT
--
-- Dashboard の「Automatically expose new tables」を切っているため、
-- service_role にも自動では権限が付かない。必要なぶんだけ明示的に渡す。
--
-- **books だけに渡す。** 他のテーブルには意図的に渡さない。
--
-- service_role は RLS を迂回する鍵なので、これでロードマップ本体を読み書きすると
-- 「アクセス制御はRLSに集約する」（CLAUDE.md 6章）が崩れる。
-- lib/supabase/admin.ts に「ロードマップ本体には絶対に使わないこと」と
-- 書いてあるが、コメントは破れる。DBの権限にしておけば破れない。
--
-- books だけが例外なのは、誰のものでもない表示用キャッシュで所有者による
-- 保護ができず、代わりに「書けるのはサーバーの1経路だけ」という形にしているため
-- （CLAUDE.md 7章）。
--
-- 将来サーバー側から別のテーブルを触る必要が出たら、そのときに
-- 「なぜRLSでは足りないのか」を確かめてからここに足すこと。
-- ============================================================================

grant select, insert, update on public.books to service_role;
